const fs=require('fs');
const path=require('path');
const esbuild=require('esbuild');
const output=path.join(__dirname,'house-3d.html');
const result=esbuild.buildSync({entryPoints:[path.join(__dirname,'house.js')],bundle:true,write:false,minify:true,format:'iife',legalComments:'inline'});
let html=fs.readFileSync(path.join(__dirname,'model.html'),'utf8');
const photos={};
for(const [name,file] of Object.entries({front:'front-approved.png',left:'left-side.png',right:'right-side.png',rear:'rear.png'}))photos[name]='data:image/png;base64,'+fs.readFileSync(path.join(__dirname,'../elevations/selected-a',file)).toString('base64');
html=html.replace('<!-- PHOTOS -->',()=>'<script>window.HMPhotos='+JSON.stringify(photos)+'</script>');
fs.writeFileSync(output,html.replace('<!-- BUNDLE -->',()=>'<script>'+result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script')+'</script>'));
console.log('Built standalone offline viewer:',output);
